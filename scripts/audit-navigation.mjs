import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';

const read = path => readFileSync(path, 'utf8');
const html = read('www/index.html');
const app = read('www/app.js');
const css = read('www/app.css');
const serviteHtml = read('www/servite.html');
const serviteCss = read('www/servite.css');
const serviteScript = read('www/servite-3.js');
const pkg = JSON.parse(read('package.json'));
const workflow = read('.github/workflows/build-apk.yml');
const loader = read('www/data/load-devotions.js');

for (const file of ['www/app.js', 'www/servite-1.js', 'www/servite-2.js', 'www/servite-3.js']) {
  const result = spawnSync(process.execPath, ['--check', file], { encoding: 'utf8' });
  assert.equal(result.status, 0, result.stderr || 'Erro de sintaxe em ' + file);
}
for (const tab of ['vida', 'liturgia', 'oracoes']) assert.ok(html.includes('data-tab="' + tab + '"'), 'Aba ausente: ' + tab);
assert.match(html, /app\.js/);
assert.match(html, /href=["'][^"']*app\.css["']/);
assert.match(app, /function officeHourButtonHtml/);
assert.match(app, /const APP_VERSION = ['"]4\.9\.42['"]/);
assert.match(workflow, /Build APK Liturgia OSM 4\.9\.42/);
assert.match(workflow, /versionCode 40946/);
assert.match(app, /rowtitle">Hoje/);
assert.match(html, /<h1>Liturgia <span class="brand-tag">OSM<\/span><\/h1>/);
assert.match(css, /\.topbar \.brand-tag/);
assert.match(app, /Abrir ofício de hoje na Paulus/);
assert.doesNotMatch(app, /liturgy-page-intro|Aqui você encontra a Missa do dia|O ofício de hoje está na Paulus\. Os textos próprios da Ordem estão logo abaixo/);
assert.doesNotMatch(app, /Abrir ofício próprio/);
assert.match(app, /Ofícios e textos próprios OSM/);
assert.doesNotMatch(app, /Hora litúrgica própria/);
assert.doesNotMatch(app, /paulusBlock/);
assert.match(app, /addListener\(['"]backButton['"]/);
assert.match(app, /function saintRankSubtitle/);
assert.match(css, /text-align:\s*center/);
assert.match(serviteHtml, /servite-3\.js/);
assert.match(serviteCss, /text-align:\s*center/);
assert.match(serviteScript, /hour-tab-btn/);
const navStart = app.indexOf('function navigationBlock(s){');
const navEnd = app.indexOf('window.renderCelebrationHub=function(id){', navStart);
const navigation = app.slice(navStart, navEnd);
assert.match(navigation, /‹ Anterior/);
assert.match(navigation, /Próxima ›/);
assert.doesNotMatch(navigation, /previous\.title|next\.title|hub-action-title/);
const ruleStart = serviteScript.indexOf('function renderRuleArticles(text){');
const ruleEnd = serviteScript.indexOf('function viewRegra(){', ruleStart);
const ruleRenderer = serviteScript.slice(ruleStart, ruleEnd);
assert.ok(ruleRenderer.includes('source.matchAll') && ruleRenderer.includes('class="rule-article"'), 'Artigos numerados devem ser renderizados separadamente');
const renderRuleArticles = new Function('escapeHtml', ruleRenderer + '; return renderRuleArticles;')(value => value);
const sampleRule = ['Introdução.', '1. Primeiro artigo.', '2. Segundo artigo.'].join('\n');
const renderedRule = renderRuleArticles(sampleRule);
assert.equal((renderedRule.match(/class="rule-article"/g) || []).length, 2, 'Cada número da Regra deve iniciar um artigo separado');
assert.equal(pkg.dependencies['@capacitor/app'], '8.1.2');
assert.match(loader, /window\.OSM_PRAYERS/);
assert.match(workflow, /assembleRelease/);
assert.match(workflow, /minifyEnabled true/);
const vidaStart = app.indexOf('function viewVida(){');
const vidaEnd = app.indexOf('function setLiturgiaSection(', vidaStart);
const vidaView = app.slice(vidaStart, vidaEnd);
assert.ok(vidaView.includes("setTab('calendario')") && vidaView.includes('viewCalendario()'), 'Calendário deve ter aba visível e destino funcional.');
const calendarStart = app.indexOf('function viewCalendario(){');
const calendarEnd = app.indexOf('function viewOSMPlus()', calendarStart);
const calendarView = app.slice(calendarStart, calendarEnd);
for (const part of ['calendar-month-select', 'calendar-toolbar', 'calendar-grid', 'Celebrações do mês']) assert.ok(calendarView.includes(part), 'Calendário incompleto: ' + part);
const calendarRowStart = app.indexOf('function calendarCelebrationRow(s){');
const calendarRowEnd = app.indexOf('\n}', calendarRowStart) + 2;
const calendarRow = app.slice(calendarRowStart, calendarRowEnd);
assert.match(calendarRow, /href="\?celebracao=\$\{s\._id\}"/);
assert.doesNotMatch(calendarRow, /calendar-entry-actions|officeClassificationForSaint|saintRankSubtitle|saintImageHtml/);
const homeStart = app.indexOf('function viewHoje(){');
const homeEnd = app.indexOf('function officeDateKey(', homeStart);
const homeView = app.slice(homeStart, homeEnd);
assert.ok(homeView.includes('home-hero') && homeView.includes('Calendário'), 'Página inicial deve preservar o cabeçalho visual e o acesso ao calendário.');
assert.ok(html.includes('<h1>Liturgia <span class="brand-tag">OSM</span></h1>'), 'Cabeçalho deve manter a marca Liturgia OSM com etiqueta.');
assert.ok(css.includes('#view .calendar-grid{display:grid;grid-template-columns:repeat(7,minmax(0,1fr))'), 'Calendário deve manter as sete colunas dentro da largura móvel.');
assert.ok(css.includes('.calendar-celebration-link{'), 'Nome da celebração deve permanecer como link legível.');
assert.ok(css.includes('#view .saint-row-hours{grid-template-columns:minmax(0,1fr);width:100%}'), 'Listas dos próprios não devem duplicar a data em um selo lateral.');
assert.ok(css.includes('#view .saint-row-hours>.office-hours-grid{grid-column:1/-1}'), 'Botões de Ofícios devem usar toda a largura disponível.');
assert.ok(css.includes('#view .hub-navigation-grid{grid-template-columns:repeat(2,minmax(0,1fr))'), 'Navegação anterior/próxima deve manter colunas equilibradas.');
const massScriptStart = app.indexOf("window.loadDailyLiturgy=async function(date){");
const massScriptEnd = app.indexOf("window.openDailyLiturgy=", massScriptStart);
assert.ok(app.slice(massScriptStart, massScriptEnd).includes("dailyLiturgyDateDisplay") && app.slice(massScriptStart, massScriptEnd).includes("dateDisplay.textContent=day+'/'+month+'/'+year"), 'A data escolhida deve aparecer no campo da Missa.');
assert.ok(!app.includes("||state.tab!=='hoje'"), 'O botão Voltar flutuante não deve cobrir as telas principais.');
assert.ok(app.includes('hub-mode-button') && app.includes("inlineBack&&!overlay"), 'Controles do santo devem ter retorno e modo celebração sem sobreposição.');
assert.ok(css.includes('body.light-mode #view .office-hour-choice{background:#f7f4ec!important'), 'Botões de Ofício precisam de contraste no tema claro.');


assert.match(workflow, /\('shrinkResources', 'true'\)/);
console.log('Auditoria aprovada: abas, módulos, botão Android, rótulos dos santos, orações JSON, Horas centralizadas e release R8.');
